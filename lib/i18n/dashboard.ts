export type DashCopy = {
  [K in keyof (typeof dict)['ht']]: string;
};

export function getDashCopy(lang: DashLang): DashCopy {
  return dict[lang] || dict.ht;
}

export function loadDashLang(): DashLang {
  if (typeof window === 'undefined') return 'ht';
  const saved = window.localStorage.getItem('hx_dash_lang');
  if (saved === 'ht' || saved === 'fr' || saved === 'en') return saved;
  return 'ht';
}

export function saveDashLang(lang: DashLang) {
  if (typeof window === 'undefined') return;
  window.localStorage.setItem('hx_dash_lang', lang);
}
